"""Rebuild the layout reference stills under assets/references/v3-reference/.

The stills are ordinary renders of the brief renderer on synthetic footage and example copy. They
show the locked layout with whichever font is passed and carry no account or third-party footage.
Run this on Windows with Microsoft YaHei Bold (the production font) whenever the lock, the renderer
or the example copy changes, then review the three images and commit them:

    python scripts/build_layout_reference.py --font C:/Windows/Fonts/msyhbd.ttc
"""
